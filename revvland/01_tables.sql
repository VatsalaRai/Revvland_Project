-- REVVLAND MOTOCROSS EVENT MANAGEMENT SYSTEM : table creation (Oracle)
-- Run as user revvland. Tables are created parents first, children after.
SET DEFINE OFF
-- 1. No foreign keys
CREATE TABLE Staff (
  Staff_ID NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
  Name VARCHAR2(100) NOT NULL,
  Role VARCHAR2(50) NOT NULL,
  Phone VARCHAR2(15) NOT NULL,
  Email VARCHAR2(100) UNIQUE
);
CREATE TABLE Rider (
  Rider_ID NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
  Name VARCHAR2(100) NOT NULL,
  Date_of_Birth DATE NOT NULL,
  Phone VARCHAR2(15) NOT NULL UNIQUE,
  Email VARCHAR2(100) UNIQUE,
  Emergency_Contact VARCHAR2(15) NOT NULL
);
CREATE TABLE Category (
  Category_ID NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
  Category_Name VARCHAR2(50) NOT NULL UNIQUE,
  Min_CC NUMBER NOT NULL,
  Max_CC NUMBER NOT NULL,
  Description VARCHAR2(200),
  CONSTRAINT ck_category_cc CHECK (Min_CC < Max_CC)
);
-- 2. Need Staff / Rider
CREATE TABLE Event (
  Event_ID NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
  Event_Name VARCHAR2(100) NOT NULL,
  Event_Date DATE NOT NULL,
  Start_Time VARCHAR2(5),
  End_Time VARCHAR2(5),
  Event_Type VARCHAR2(30),
  Status VARCHAR2(15) DEFAULT 'Planned' NOT NULL CHECK (Status IN ('Planned','Open','Completed','Cancelled')),
  Staff_ID NUMBER REFERENCES Staff(Staff_ID)
);
CREATE TABLE Bike (
  Bike_ID NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
  Rider_ID NUMBER NOT NULL REFERENCES Rider(Rider_ID),
  Bike_Number VARCHAR2(10) NOT NULL UNIQUE,
  Brand VARCHAR2(50),
  Model VARCHAR2(50),
  Engine_CC NUMBER NOT NULL CHECK (Engine_CC > 0)
);
-- 3. Need Rider + Event + Category
CREATE TABLE Registration (
  Registration_ID NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
  Rider_ID NUMBER NOT NULL REFERENCES Rider(Rider_ID) ON DELETE CASCADE,
  Event_ID NUMBER NOT NULL REFERENCES Event(Event_ID),
  Category_ID NUMBER NOT NULL REFERENCES Category(Category_ID),
  Registration_Date DATE DEFAULT SYSDATE NOT NULL,
  Registration_Status VARCHAR2(15) DEFAULT 'Pending' NOT NULL CHECK (Registration_Status IN ('Pending','Confirmed','Cancelled')),
  CONSTRAINT uq_reg_rider_event UNIQUE (Rider_ID, Event_ID)
);
CREATE TABLE Race (
  Race_ID NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
  Event_ID NUMBER NOT NULL REFERENCES Event(Event_ID),
  Category_ID NUMBER NOT NULL REFERENCES Category(Category_ID),
  Race_Name VARCHAR2(100) NOT NULL,
  Race_Date DATE NOT NULL,
  Start_Time VARCHAR2(5),
  Number_of_Laps NUMBER CHECK (Number_of_Laps > 0)
);
CREATE TABLE Track_Booking (
  Booking_ID NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
  Event_ID NUMBER NOT NULL REFERENCES Event(Event_ID),
  Booking_Date DATE NOT NULL,
  Start_Time VARCHAR2(5) NOT NULL,
  End_Time VARCHAR2(5) NOT NULL,
  Booking_Status VARCHAR2(15) DEFAULT 'Pending' NOT NULL CHECK (Booking_Status IN ('Pending','Confirmed','Cancelled')),
  CONSTRAINT ck_booking_time CHECK (Start_Time < End_Time)
);
-- 4. Need Registration / Race / Bike
CREATE TABLE Payment (
  Payment_ID NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
  Registration_ID NUMBER NOT NULL REFERENCES Registration(Registration_ID),
  Amount NUMBER(10,2) NOT NULL CHECK (Amount >= 0),
  Payment_Date DATE,
  Payment_Method VARCHAR2(20) CHECK (Payment_Method IN ('UPI','Card','Cash','Net Banking')),
  Payment_Status VARCHAR2(15) DEFAULT 'Pending' NOT NULL CHECK (Payment_Status IN ('Pending','Paid','Failed','Refunded')),
  Transaction_Reference VARCHAR2(40) UNIQUE
);
CREATE TABLE Race_Participant (
  Race_ID NUMBER NOT NULL REFERENCES Race(Race_ID),
  Rider_ID NUMBER NOT NULL REFERENCES Rider(Rider_ID),
  Bike_ID NUMBER NOT NULL REFERENCES Bike(Bike_ID),
  Gate_Number NUMBER CHECK (Gate_Number > 0),
  CONSTRAINT pk_race_participant PRIMARY KEY (Race_ID, Rider_ID),
  CONSTRAINT uq_race_gate UNIQUE (Race_ID, Gate_Number)
);
-- 5. Needs Race + Rider
CREATE TABLE Result (
  Result_ID NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
  Race_ID NUMBER NOT NULL REFERENCES Race(Race_ID),
  Rider_ID NUMBER NOT NULL REFERENCES Rider(Rider_ID),
  Position NUMBER CHECK (Position > 0),
  Lap_Time NUMBER(7,3),
  Total_Time NUMBER(8,3),
  Points NUMBER DEFAULT 0 NOT NULL,
  Status VARCHAR2(15) DEFAULT 'Finished' NOT NULL CHECK (Status IN ('Finished','DNF','DNS','Disqualified')),
  CONSTRAINT uq_result_race_rider UNIQUE (Race_ID, Rider_ID)
);
SELECT table_name FROM user_tables ORDER BY table_name;
